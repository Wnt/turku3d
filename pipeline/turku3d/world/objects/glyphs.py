NARROW = {"1": 3.2, "I": 1.6, ".": 1.6, ",": 1.6, ":": 1.6, "(": 2.4, ")": 2.4, " ": 2.4, "-": 3.2, "–": 3.2}
GAP = 1.5


def text_width(text: str, height: float) -> float:
    units = sum(NARROW.get(c, 4.0) + GAP for c in text.upper()) - GAP if text else 0.0
    return units * height / 6.0


def text_shape(text: str, height: float, weight: float = 0.13, centre: tuple[float, float] = (0.0, 0.0)):
    """One line of text as a geometry: cap height `height` (m), stroke width `weight` of it, centred on `centre`."""
    lines, x = [], 0.0
    for char in text.upper():
        width = NARROW.get(char, 4.0)
        shift = (width - 4.0) / 2
        for stroke in STROKES.get(char, []):
            lines.append(shapely.LineString([(x + px + shift, py) for px, py in stroke]))
        x += width + GAP
    if not lines:
        return shapely.Polygon()
    shape = shapely.MultiLineString(lines).buffer(6.0 * weight / 2, quad_segs=1, cap_style="square", join_style="bevel")
    scale = height / 6.0
    shape = affinity.scale(shape, scale, scale, origin=(0, 0))
    total = (x - GAP) * scale
    return affinity.translate(shape, centre[0] - total / 2, centre[1] - height / 2)
